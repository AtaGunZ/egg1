"""Build rules/kayseri.rules.json + rules/RULES.md from rules_spec.py and regulation/articles.json.
Run: python tools/regulation/build_rules.py   (after python -m bimcheck.regulation.extract)"""
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
from bimcheck.regulation.catalogue import make_rule_id, validate_catalogue  # noqa: E402
from regulation.rules_spec import RULES  # noqa: E402


def find(arts, art, par, item):
    a = next(x for x in arts if x["article"] == art)
    p = next(x for x in a["paragraphs"] if x["no"] == par)
    node, ctx = p, []
    if item:
        cur = p
        for i, part in enumerate(item.split(".")):
            nxt = next((c for c in cur.get("items", []) if c["key"] == part), None)
            if nxt is None:
                break  # synthetic key -> paragraph text
            ctx.append(cur["text"].split("\n")[0])
            cur = nxt
        node = cur
    return a, node, ctx


def rev_note(node):
    revs = node.get("revisions", [])
    if not revs:
        return None
    parts, i = [], 0
    while i < len(revs):
        r = revs[i]
        if r["type"] == "deleted" and i + 1 < len(revs) and revs[i + 1]["type"] == "added":
            parts.append(f"'{r['text'][:80]}' -> '{revs[i+1]['text'][:80]}'"); i += 2
        else:
            parts.append(("added: " if r["type"] == "added" else "removed: ") + f"'{r['text'][:80]}'"); i += 1
    return "2022 redline: " + "; ".join(parts)


def main():
    arts = json.loads((ROOT / "regulation" / "articles.json").read_text(encoding="utf-8"))
    out = []
    for s in RULES:
        a, node, ctx = find(arts, s["article"], s["paragraph"], s["item"])
        status = node.get("status", "kept")
        if s["rev_note"]:
            rev = {"status": "amended" if status != "added" else "new", "note": s["rev_note"]}
        elif status == "kept":
            rev = {"status": "current", "note": None}
        else:
            rev = {"status": "new" if status == "added" else "amended", "note": rev_note(node)}
        out.append({
            "id": make_rule_id(s["article"], s["paragraph"], s["item"]), "article": s["article"], "paragraph": s["paragraph"],
            "item": s["item"], "title_tr": s["title_tr"], "title_en": s["title_en"], "text_tr": node["text"], "page": node["page"],
            "category": s["category"], "automation": s["automation"], "requires": s["requires"], "severity": s["severity"],
            "applies_when": s["applies_when"], "check": s["check"], "unit_display": s["unit_display"], "revision": rev,
            "notes": s["notes"],
            "extra": {"needs": s["needs"], "delegates_to": s["delegates_to"], "alt_requires": s["alt_requires"],
                      "context_tr": ctx, "article_title": a["title"]},
        })
    cat = {"schema_version": "1", "regulation": {"id": "kbb-imar-2022", "title": "Kayseri BB İmar Yönetmeliği", "version": "14.02.2022",
           "source_pdf": "regulation/kayseri-imar-yonetmeligi-2022-lejantli.pdf"}, "rules": out}
    errs = validate_catalogue(cat)
    if errs:
        print("\n".join(errs)); sys.exit(1)
    (ROOT / "rules" / "kayseri.rules.json").write_text(json.dumps(cat, ensure_ascii=False, indent=1), encoding="utf-8")
    by = defaultdict(list)
    for r in out:
        by[r["article"]].append(r)
    L = ["# Rule coverage (generated by tools/regulation/build_rules.py)", "",
         "automation: auto = engine decides; semi = engine pre-screens, edge cases -> review; manual = catalogued for the reviewer.", "",
         "| Madde | rule id | automation | needed to check |", "|---|---|---|---|"]
    for art in sorted(by):
        for r in by[art]:
            L.append(f"| {art} | {r['id']} | {r['automation']} | {r['extra']['needs'][:110]} |")
    L += ["", "## Delegated to regulations NOT in the PDF", "",
          "- Planlı Alanlar İmar Yönetmeliği (RG 30113): Madde 5, 19, 20 (TAKS), 54-57, 64-69 and definitions used by 21/23.",
          "- Binaların Yangından Korunması Hakkında Yönetmelik: escape widths (31-1-a), shelters, tanks, fire lifts (34-4).",
          "- TS 9111 / erişilebilirlik standartları: 29-5, 30-8..13, 31-1-ç, 34-9/10, 48.",
          "- Asansör Yönetmeliği 2014/33/AB, TS EN 81-70: 34-7.",
          "- Otopark, Sığınak, Binalarda Enerji Performansı, Türkiye Bina Deprem Yönetmelikleri: 27-1-ç, 39-3.",
          "- İşyeri Açma ve Çalışma Ruhsatları Yönetmeliği (33-3, 46), Alışveriş Merkezleri Yönetmeliği (47-2), 634 sayılı Kat Mülkiyeti Kanunu (23-7).",
          "- Articles 1-5, 7-8, 10-19, 24-26, 35, 46, 50, 53-59 and annex forms (EK-1..) are procedural/definitional; only quantitative items are catalogued."]
    (ROOT / "rules" / "RULES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    from collections import Counter
    print(len(out), Counter(r["automation"] for r in out))


main()
